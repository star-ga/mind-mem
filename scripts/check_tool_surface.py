#!/usr/bin/env python3
"""Reachability, applied to the MCP tool surface.

The 5.0.0 sweep deleted 44 modules that no product code imported. The
generator of that debt was not the modules -- it was shipping surface before
consumers -- and the 98-tool MCP list is the most public instance of the same
habit. For an agent choosing what to call, a long tool list is a COST, not a
feature.

This does not (and cannot) measure what real clients call; there is no
telemetry and inventing one would be worse than the gap. What it measures is
whether each registered tool is *supported* anywhere a caller could learn it
from:

    tested       exercised by the test suite
    documented   named in docs/ or README
    trained      present in the 4b training corpus under train/

A tool that is none of the three is registered and unsupported: nothing
teaches it, nothing proves it, and nothing would notice if it broke. That is
the tool-surface twin of "no caller, no tick".

It also keeps ``docs/api-reference.md`` honest about the registry: the
reference carries a generated index of every registered tool (name, ACL scope,
owning module, parameters, summary) rendered from the live server, and
``--check-doc-names`` fails when that index is stale, when a registered tool has
no row, or when a row names a tool the registry does not have.

Usage:
    python3 scripts/check_tool_surface.py                    # report
    python3 scripts/check_tool_surface.py --check N          # exit 1 if unsupported > N
    python3 scripts/check_tool_surface.py --check-doc-names  # exit 1 on doc/registry drift
    python3 scripts/check_tool_surface.py --write-api-index  # regenerate the reference index
"""

from __future__ import annotations

import argparse
import asyncio
import pathlib
import re
import sys
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "mind_mem"
API_REF = ROOT / "docs" / "api-reference.md"

INDEX_BEGIN = "<!-- tool-index:begin (generated by scripts/check_tool_surface.py --write-api-index; do not edit by hand) -->"
INDEX_END = "<!-- tool-index:end -->"


def registered_tools() -> list[str]:
    """Every name passed to `mcp.tool(...)` across the tool modules."""
    names: set[str] = set()
    for path in (SRC / "mcp" / "tools").rglob("*.py"):
        text = path.read_text(encoding="utf-8", errors="replace")
        names.update(re.findall(r"mcp\.tool\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)", text))
    return sorted(names)


def _corpus(paths: list[pathlib.Path], suffixes: tuple[str, ...]) -> str:
    out = []
    for base in paths:
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if path.suffix in suffixes and "__pycache__" not in path.parts:
                try:
                    out.append(path.read_text(encoding="utf-8", errors="replace"))
                except OSError:
                    continue
    return "\n".join(out)


def support_matrix() -> dict[str, dict[str, bool]]:
    tools = registered_tools()
    tested = _corpus([ROOT / "tests"], (".py",))
    documented = _corpus([ROOT / "docs"], (".md",)) + (
        (ROOT / "README.md").read_text(encoding="utf-8", errors="replace") if (ROOT / "README.md").exists() else ""
    )
    trained = _corpus([ROOT / "train"], (".py", ".md", ".json", ".jsonl"))

    matrix = {}
    for tool in tools:
        word = re.compile(rf"\b{re.escape(tool)}\b")
        matrix[tool] = {
            "tested": bool(word.search(tested)),
            "documented": bool(word.search(documented)),
            "trained": bool(word.search(trained)),
        }
    return matrix


#: Tool-shaped names a doc may use that are NOT MCP tools. Each needs a reason.
_NOT_A_TOOL: dict[str, str] = {
    # English connectives that survive the comma-run match.
    "and": "conjunction",
    "more": "as in 'and 62 more'",
    "the": "article",
    "total": "as in '(98 total)'",
    "full": "prose",
    "list": "prose",
    "see": "prose",
}


def ghost_tool_names(real: set[str]) -> dict[str, list[str]]:
    """Tool-shaped names the docs claim that the registry does not have.

    A doc naming a tool that does not exist is worse than an undocumented tool:
    it sends a caller to a surface that will fail, and it reads as authoritative.
    CLAUDE.md carried ELEVEN of these (create_snapshot, list_snapshots,
    restore_snapshot, briefing, cross_encoder_rerank, delete_memory,
    import_memory, audit_replay, tier_decay_apply, encrypt_status,
    alerts_subscribe) -- surfaces that were renamed or never shipped.

    Scoped deliberately to the curated TOOL LISTS, not to prose: matching every
    snake_case token in every document would flag ordinary function names and
    the gate would be turned off within a week. A "tool list" here is a
    comma-separated run of >= 6 tool-shaped names, which is the shape these
    lists actually take.
    """
    docs = [ROOT / "CLAUDE.md", ROOT / "README.md"] + sorted((ROOT / "docs").glob("*.md"))
    out: dict[str, list[str]] = {}

    # Scoped to lists under an explicit "MCP Tools" heading -- NOT a heuristic
    # scrape of every comma-run in the corpus. Two earlier attempts show why:
    # requiring an underscore on every element made the gate unable to fail at
    # all (the real lists mix `recall` with `hybrid_search`), and dropping that
    # requirement flagged parameter names in guardrails.md and edge types in the
    # 4b README. A gate that cries wolf gets switched off, and a gate that
    # cannot fire is worse than none, so the trigger is an explicit marker a
    # writer opts into rather than something inferred from prose.
    heading = re.compile(r"^#{1,6}\s+.*\bMCP Tools?\b.*$", re.I | re.M)
    ident = re.compile(r"\b[a-z][a-z0-9_]{2,}\b")

    for doc in docs:
        if not doc.is_file():
            continue
        text = doc.read_text(encoding="utf-8", errors="replace")
        named: set[str] = set()
        for match in heading.finditer(text):
            block = text[match.end() : match.end() + 1800]
            nxt = re.search(r"^#{1,6}\s", block, re.M)
            if nxt:
                block = block[: nxt.start()]
            # A run counts as a TOOL LIST only when most of it already names
            # real tools. Self-calibrating, and it settles every false positive
            # the earlier versions produced: a parameter list, a file-format
            # list, and an edge-type list all score ~0% and are ignored, while a
            # genuine list with one bad name scores high and the bad name is
            # reported. It also spares this file's own prose about which ghosts
            # USED to be listed, which is otherwise indistinguishable by shape.
            for run in re.finditer(r"(?:[a-z][a-z0-9_]{2,}\s*,\s*){3,}[a-z][a-z0-9_]{2,}", block):
                tokens = [t for t in ident.findall(run.group(0)) if t not in _NOT_A_TOOL]
                if not tokens:
                    continue
                hits = sum(1 for t in tokens if t in real)
                if hits / len(tokens) >= 0.6:
                    named |= set(tokens)
        ghosts = sorted(n for n in named - real if n not in _NOT_A_TOOL)
        if ghosts:
            out[doc.relative_to(ROOT).as_posix()] = ghosts
    return out


# ---------------------------------------------------------------------------
# docs/api-reference.md <-> registry
# ---------------------------------------------------------------------------

_MCP_SECTION = re.compile(r"^##\s+MCP Server\b.*$", re.M)
_TABLE_ROW_NAME = re.compile(r"^\|\s*`([A-Za-z_][A-Za-z0-9_]*)`\s*\|", re.M)


def _mcp_section(text: str) -> str:
    """The ``## MCP Server`` section: from its heading to the next level-2 heading."""
    m = _MCP_SECTION.search(text)
    if not m:
        return ""
    rest = text[m.end() :]
    nxt = re.search(r"^##\s", rest, re.M)
    return rest[: nxt.start()] if nxt else rest


def api_reference_drift(text: str, real: set[str]) -> dict[str, list[str]]:
    """Tool rows in the MCP section of the reference vs the registry.

    ``ghosts``: a row's first cell names a tool the registry does not have.
    ``missing``: a registered tool with no row anywhere in the section.
    Rows outside ``## MCP Server`` (the Python API) are not tool claims.
    """
    named = set(_TABLE_ROW_NAME.findall(_mcp_section(text)))
    return {"ghosts": sorted(named - real), "missing": sorted(real - named)}


def _summary(description: str | None) -> str:
    para = (description or "").strip().split("\n\n", 1)[0]
    flat = " ".join(para.split())
    cut = re.search(r"(?<=[.!?])\s", flat)
    if cut:
        flat = flat[: cut.start()]
    return flat.replace("|", "\\|") or "-"


def live_registry() -> list[dict[str, Any]]:
    """Every tool the server actually registers, read from the live FastMCP instance.

    Imports the package (fastmcp included). The static ``registered_tools``
    regex is enough for counting; the reference index needs what a client is
    served -- parameters, required-ness and the ACL scope -- so it asks the
    server rather than re-deriving them.
    """
    src = str(ROOT / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    from mind_mem.mcp.infra.acl import ADMIN_TOOLS
    from mind_mem.mcp.server import mcp

    rows: list[dict[str, Any]] = []
    for tool in asyncio.run(mcp.list_tools()):
        schema = tool.parameters or {}
        required = set(schema.get("required", []))
        params = [(name, name in required) for name in (schema.get("properties") or {})]
        rows.append(
            {
                "name": tool.name,
                "scope": "admin" if tool.name in ADMIN_TOOLS else "user",
                "module": tool.fn.__module__.rsplit(".", 1)[-1],
                "params": params,
                "summary": _summary(tool.description),
            }
        )
    return sorted(rows, key=lambda r: r["name"])


def render_api_index(rows: list[dict[str, Any]]) -> str:
    """The generated index body (between the markers), one row per tool."""
    out = [
        "",
        f"All {len(rows)} registered tools, generated from the live registry. "
        "`[param]` is optional; scope `admin` needs an admin-scoped token.",
        "",
        "| Tool | Scope | Module | Parameters | Summary |",
        "|------|-------|--------|------------|---------|",
    ]
    for r in rows:
        params = ", ".join(f"`{n}`" if req else f"`[{n}]`" for n, req in r["params"]) or "-"
        out.append(f"| `{r['name']}` | {r['scope']} | `{r['module']}` | {params} | {r['summary']} |")
    out.append("")
    return "\n".join(out)


def extract_api_index(text: str) -> str | None:
    start = text.find(INDEX_BEGIN)
    end = text.find(INDEX_END)
    if start < 0 or end < start:
        return None
    return text[start + len(INDEX_BEGIN) : end]


def write_api_index(path: pathlib.Path | None = None) -> bool:
    """Rewrite the generated index in place. Returns True when the file changed."""
    path = path or API_REF
    text = path.read_text(encoding="utf-8")
    if extract_api_index(text) is None:
        raise SystemExit(f"{path}: index markers not found")
    start = text.find(INDEX_BEGIN) + len(INDEX_BEGIN)
    end = text.find(INDEX_END)
    new = text[:start] + render_api_index(live_registry()) + text[end:]
    if new != text:
        path.write_text(new, encoding="utf-8")
        return True
    return False


_HAND_ROW = re.compile(r"^\|\s*`([A-Za-z_][A-Za-z0-9_]*)`\s*\|(.*)\|\s*$")


def hand_table_param_drift(text: str, rows: list[dict[str, Any]]) -> list[str]:
    """Hand-written rows whose parameter cell names a parameter the tool lacks.

    The last cell of a hand-written row lists key parameters. Backticked
    identifiers outside parentheses must be real parameters of that tool;
    parenthesised text carries allowed VALUES (``(`cites`/`refines`)``) and is
    not a parameter claim. Rows of the generated index are excluded -- they are
    checked by regeneration.
    """
    params = {r["name"]: {p for p, _ in r["params"]} for r in rows}
    section = _mcp_section(text)
    begin = section.find(INDEX_BEGIN)
    if begin >= 0:
        end = section.find(INDEX_END, begin)
        section = section[:begin] + (section[end + len(INDEX_END) :] if end >= 0 else "")
    out: list[str] = []
    for line in section.splitlines():
        m = _HAND_ROW.match(line)
        if not m or m.group(1) not in params:
            continue
        cells = [c.strip() for c in m.group(2).split("|")]
        if len(cells) < 2:
            continue
        claimed = re.findall(r"`([A-Za-z_][A-Za-z0-9_]*)`", re.sub(r"\([^)]*\)", "", cells[-1]))
        out.extend(f"{m.group(1)}: `{name}`" for name in claimed if name not in params[m.group(1)])
    return out


def api_reference_problems() -> list[str]:
    """Every way docs/api-reference.md disagrees with the registry (empty = aligned)."""
    text = API_REF.read_text(encoding="utf-8")
    problems: list[str] = []
    drift = api_reference_drift(text, set(registered_tools()))
    for name in drift["ghosts"]:
        problems.append(f"names `{name}`, which is not a registered tool")
    for name in drift["missing"]:
        problems.append(f"has no row for registered tool `{name}`")
    rows = live_registry()
    for bad in hand_table_param_drift(text, rows):
        problems.append(f"lists a parameter the tool does not take: {bad}")
    current = extract_api_index(text)
    if current is None:
        problems.append("has no generated tool index (markers missing)")
    elif current != render_api_index(rows):
        problems.append("generated tool index is stale; run scripts/check_tool_surface.py --write-api-index")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", type=int, metavar="N", help="exit 1 when more than N tools are unsupported")
    ap.add_argument(
        "--check-doc-names",
        action="store_true",
        help="exit 1 when a doc tool-list names a tool that does not exist, or docs/api-reference.md drifts",
    )
    ap.add_argument("--write-api-index", action="store_true", help="regenerate the tool index in docs/api-reference.md")
    args = ap.parse_args(argv)

    if args.write_api_index:
        changed = write_api_index()
        print(f"{API_REF.relative_to(ROOT).as_posix()}: {'updated' if changed else 'already current'}")
        return 0

    matrix = support_matrix()
    unsupported = sorted(t for t, m in matrix.items() if not any(m.values()))
    undocumented = sorted(t for t, m in matrix.items() if not m["documented"])
    untested = sorted(t for t, m in matrix.items() if not m["tested"])

    print(f"registered tools: {len(matrix)}")
    print(f"  untested       : {len(untested)}")
    print(f"  undocumented   : {len(undocumented)}")
    print(f"  UNSUPPORTED    : {len(unsupported)}  (in none of tested/documented/trained)")
    if untested:
        print("\nuntested:")
        for t in untested:
            print(f"  - {t}")
    if undocumented:
        print("\nundocumented:")
        for t in undocumented:
            print(f"  - {t}")
    if unsupported:
        print("\nUNSUPPORTED (registered, and nothing teaches or proves it):")
        for t in unsupported:
            print(f"  ! {t}")

    ghosts = ghost_tool_names(set(matrix))
    if ghosts:
        print("\nGHOST TOOL NAMES (documented, not registered):")
        for doc, names in ghosts.items():
            print(f"  {doc}: {', '.join(names)}")

    if args.check_doc_names and ghosts:
        total = sum(len(v) for v in ghosts.values())
        print(f"\nFAIL: {total} documented tool name(s) do not exist", file=sys.stderr)
        return 1

    if args.check_doc_names:
        try:
            problems = api_reference_problems()
        except ImportError as exc:
            # A verifier that cannot run is not one that passed.
            print(f"\nERROR: cannot load the live registry to check docs/api-reference.md: {exc}", file=sys.stderr)
            return 2
        if problems:
            print("\nAPI REFERENCE DRIFT (docs/api-reference.md):", file=sys.stderr)
            for p in problems:
                print(f"  - {p}", file=sys.stderr)
            return 1

    if args.check is not None and len(unsupported) > args.check:
        print(f"\nFAIL: {len(unsupported)} unsupported tools > allowed {args.check}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
